#!/usr/bin/env python3
"""Generate the public Dawn GPU identity tables using only the stdlib."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/dawn/src/dawn/gpu_info.json"
OUTPUT = ROOT / "yawgpu-hal/src/gpu_info_data.rs"


def js_enum_case(name):
    chunks = name.split(" ")
    result = chunks[0].lower()
    for chunk in chunks[1:]:
        if not result[-1].isdigit():
            result += "-"
        result += chunk.lower()
    return result


def generate():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    lines = [
        "// Generated by tools/gen_gpu_info.py; do not edit.",
        "// Source: third_party/dawn/src/dawn/gpu_info.json",
        *[("// " + line).rstrip() for line in data["_comment"]],
        "",
        "#[rustfmt::skip]",
        "pub(super) const VENDORS: &[(u32, &str)] = &[",
    ]
    sets = []
    for name, vendor in data["vendors"].items():
        if name.startswith("_"):
            continue
        vendor_id = int(vendor["id"], 0)
        lines.append(f'    (0x{vendor_id:x}, "{js_enum_case(vendor.get("name_override", name))}"),')
        for devices in vendor.get("devices", []):
            if devices.get("internal", False):
                continue
            mask = int(devices.get("mask") or "0xffffffff", 0)
            for arch, ids in devices.get("architecture", {}).items():
                if arch.startswith("_"):
                    continue
                ids = ", ".join(f"0x{int(device, 0):x}" for device in ids)
                sets.append(f'    (0x{vendor_id:x}, 0x{mask:x}, "{js_enum_case(arch)}", &[{ids}]),')
    lines += ["];", "", "#[rustfmt::skip]",
              "pub(super) const ARCHITECTURES: &[(u32, u32, &str, &[u32])] = &["]
    return "\n".join(lines + sets + ["];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "GPU info table is stale; run tools/gen_gpu_info.py\n")
        print("GPU info table is current")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
